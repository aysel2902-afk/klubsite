/* ---- köməkçi: qarışdırma ---- */
function shuffle(arr){
  const a = arr.slice();
  for (let i = a.length - 1; i > 0; i--){
    const j = Math.floor(Math.random() * (i + 1));
    [a[i], a[j]] = [a[j], a[i]];
  }
  return a;
}

/* ---- köməkçi: boşluqlu cümlə yaratmaq ---- */
function makeFillgap(sentence){
  const tokens = sentence.split(' ');
  let idx = tokens.length - 1;
  let word = tokens[idx].replace(/[.?!]$/, '');
  if (!word && tokens.length > 1){ idx = tokens.length - 2; word = tokens[idx]; }
  const trailingPunct = /[.?!]$/.test(tokens[idx]) ? tokens[idx].slice(-1) : '';
  const blanked = tokens.slice();
  blanked[idx] = '___' + trailingPunct;
  return { sentence: blanked.join(' '), answer: word };
}

/* ---- köməkçi: sözün artiklini tapmaq (sub = 'isim (der/die/das)' və ya de = 'der/die/das ...') ---- */
function getNounArticle(w){
  if (w.sub && /^isim\s*\((der|die|das)\)/i.test(w.sub)){
    return w.sub.match(/\((der|die|das)\)/i)[1].toLowerCase();
  }
  const first = (w.de || '').split(' ')[0].toLowerCase();
  if (['der', 'die', 'das'].includes(first)) return first;
  return null;
}

/* ---- köməkçi: sözdə bəzi hərfləri boşaltmaq (artikl saxlanılır, kökdə hərflər boşalır) ---- */
function makeMissingLetters(w){
  const full = w.de;
  const parts = full.split(' ');
  const article = ['der', 'die', 'das'].includes((parts[0] || '').toLowerCase()) ? parts[0] : null;
  const stemWords = article ? parts.slice(1) : parts;
  const stem = stemWords.join(' ');
  const letters = stem.split('');
  // boşaldılacaq mövqelər: hərf olan simvollardan ~40%, amma ilk hərf həmişə qalır
  const letterIdxs = [];
  letters.forEach((ch, i) => { if (/[a-zA-ZäöüßÄÖÜ]/.test(ch) && i !== 0) letterIdxs.push(i); });
  const blankCount = Math.max(1, Math.min(letterIdxs.length, Math.round(letterIdxs.length * 0.4)));
  const chosen = shuffle(letterIdxs).slice(0, blankCount).sort((a, b) => a - b);
  const display = letters.map((ch, i) => chosen.includes(i) ? '_' : ch);
  return {
    article: article,
    displayStem: display.join(''),
    fullStem: stem,
    blanks: chosen.map(i => letters[i]),
    blankIdxs: chosen,
  };
}

/* ---- köməkçi: mərhələ üçün tapşırıq siyahısını avtomatik yaratmaq ----
   items: [{type:'word'|'sentence', de, az, sub}] */
function generateExerciseQueue(items){
  const words = items.filter(w => w.type !== 'sentence');
  const sentences = items.filter(w => w.type === 'sentence');
  const allAz = items.map(w => w.az);
  const queue = [];

  words.forEach((w) => {
    const poolAz = allAz.filter(a => a !== w.az);
    const distractors = shuffle(poolAz).slice(0, 3);
    const options = shuffle([w.az, ...distractors]);
    queue.push({ type: 'mcq', prompt: '"' + w.de + '" nə deməkdir?', options: options, correct: w.az, wordKeys: [w.de] });
  });

  // "sözdə buraxılmış hərfləri tapın" — kökdə hərflər boşaldılır, istifadəçi doldurur
  words.forEach((w) => {
    const hasArticle = ['der', 'die', 'das'].includes(w.de.split(' ')[0].toLowerCase());
    const stemWords = w.de.split(' ').slice(hasArticle ? 1 : 0);
    if (stemWords.length !== 1) return; // yalnız tək söz (ifadə/cümlə yox)
    const stemLetters = stemWords.join('').replace(/[^a-zA-ZäöüßÄÖÜ]/g, '');
    if (stemLetters.length < 4) return;
    const ml = makeMissingLetters(w);
    if (!ml.blanks.length) return;
    queue.push({
      type: 'missingletters',
      article: ml.article,
      displayStem: ml.displayStem,
      fullStem: ml.fullStem,
      hintAz: w.az,
      answer: ml.fullStem,
      wordKeys: [w.de],
    });
  });

  // "düzgün artikli tapın" — isimlər üçün der/die/das seçimi (mütləq olmalıdır)
  words.forEach((w) => {
    const article = getNounArticle(w);
    if (!article) return;
    const stem = w.de.split(' ').slice(1).join(' ') || w.de;
    queue.push({
      type: 'article',
      stem: stem,
      hintAz: w.az,
      options: ['der', 'die', 'das'],
      correct: article,
      wordKeys: [w.de],
    });
  });

  for (let i = 0; i < words.length; i += 4){
    const chunk = words.slice(i, i + 4);
    if (chunk.length >= 2){
      queue.push({ type: 'match', pairs: chunk.map(function(w){ return { de: w.de, az: w.az }; }), wordKeys: chunk.map(w => w.de) });
    }
  }

  sentences.forEach((s, idx) => {
    const poolAz = allAz.filter(a => a !== s.az);
    const distractors = shuffle(poolAz).slice(0, 3);
    const options = shuffle([s.az, ...distractors]);
    queue.push({ type: 'mcq', prompt: '"' + s.de + '" nə deməkdir?', options: options, correct: s.az, wordKeys: [s.de] });

    if (idx % 2 === 0){
      const fg = makeFillgap(s.de);
      queue.push({ type: 'fillgap', sentence: fg.sentence, answer: [fg.answer], wordKeys: [s.de] });
    } else {
      queue.push({ type: 'sentence', tokens: s.de.split(' '), answer: s.de, wordKeys: [s.de] });
    }
  });

  return shuffle(queue);
}

/* ============================================================
   KURSLAR — hər səviyyənin mərhələləri (stages)
   wordCount: siyahıda göstərilən hədəf say (10, 15, 20, 25, 30 ...)
   free: true olan yalnız ilk 2 mərhələdir, qalanı abunə tələb edir
   words: yalnız pulsuz mərhələlər üçün tam dolduruldu
   ============================================================ */

const STAGE_SLOT_COUNT = 10; // hər səviyyədə 10 mərhələ (dərs)
const STAGE_WORD_COUNT = 100; // hər mərhələdə 100 kart (söz/ifadə/cümlə)

function buildStages(freeStagesData){
  const stages = freeStagesData.map((s, i) => ({
    id: i + 1, wordCount: s.words.length, free: true, words: s.words,
  }));
  for (let i = freeStagesData.length; i < STAGE_SLOT_COUNT; i++){
    stages.push({ id: i + 1, wordCount: STAGE_WORD_COUNT, free: false, words: [] });
  }
  return stages;
}

