/* ---- hər səviyyədə mərhələ sayı və bir mərhələdəki kart sayı (saytdakı söz sayına uyğun) ----
   A1 ~800 = 8×100, A2 ~1 000 = 10×100, B1 ~2 000 = 20×100, B2 / C1 / C2 ~5 000 = 20×250 */
const STAGE_PLAN = {
  a1: { stages: 8,  perStage: 100 },
  a2: { stages: 10, perStage: 100 },
  b1: { stages: 20, perStage: 100 },
  b2: { stages: 20, perStage: 250 },
  c1: { stages: 20, perStage: 250 },
  c2: { stages: 20, perStage: 250 },
};
COURSES.forEach(c => {
  const plan = STAGE_PLAN[c.id];
  if (!plan) return;
  while (c.stages.length < plan.stages){
    c.stages.push({ id: c.stages.length + 1, wordCount: plan.perStage, free: false, words: [] });
  }
  c.stages.length = plan.stages;
  c.stages.forEach(st => { if (!st.words.length) st.wordCount = plan.perStage; });
});

/* ---- əlavə mərhələ sözləri (words-*.js faylları) ----
   Format: hər sətir "almanca|azərbaycanca|kod"; kod: n=isim (artikl almanca sözdən), v=feil, a=sifət,
   z=zərf, i=ifadə, e=ədəd, p=əvəzlik, b=bağlayıcı, o=sözönü, s=cümlə */
const WORD_CODES = { v:'feil', a:'sifət', z:'zərf', i:'ifadə', e:'ədəd', p:'əvəzlik', b:'bağlayıcı', o:'sözönü' };
function parseWordLines(text){
  return text.split('\n').map(l => l.trim()).filter(Boolean).map(l => {
    const [de, az, code] = l.split('|').map(x => (x || '').trim());
    if (code === 's') return { type: 'sentence', de: de, az: az };
    if (code === 'n'){
      const art = de.split(' ')[0].toLowerCase();
      return { type: 'word', de: de, sub: ['der','die','das'].includes(art) ? 'isim (' + art + ')' : 'isim (cəm)', az: az };
    }
    return { type: 'word', de: de, sub: WORD_CODES[code] || 'söz', az: az };
  });
}
function addStageWords(levelId, stageId, text){
  const c = COURSES.find(x => x.id === levelId);
  if (!c) return;
  const st = c.stages.find(x => x.id === stageId);
  if (!st) return;
  st.words = parseWordLines(text);
  st.wordCount = st.words.length;
  st.free = true;
}


function appendStageWords(levelId, stageId, text){
  const c = COURSES.find(x => x.id === levelId);
  if (!c) return;
  const st = c.stages.find(x => x.id === stageId);
  if (!st) return;
  const have = new Set(st.words.map(w => w.de.toLowerCase()));
  const extra = parseWordLines(text).filter(w => !have.has(w.de.toLowerCase()));
  const ws = st.words.filter(w => w.type !== 'sentence').concat(extra.filter(w => w.type !== 'sentence'));
  const ss = st.words.filter(w => w.type === 'sentence').concat(extra.filter(w => w.type === 'sentence'));
  st.words = ws.concat(ss);
  st.wordCount = st.words.length;
  st.free = true;
}

/* ---- köməkçi funksiyalar ---- */
function getCourse(id){ return COURSES.find(c => c.id === id) || null; }
function getStage(courseId, stageId){
  const c = getCourse(courseId);
  if (!c) return null;
  return c.stages.find(s => s.id === Number(stageId)) || null;
}
function buildWordBank(){
  const words = [];
  COURSES.forEach(course => {
    course.stages.forEach(stage => {
      stage.words.forEach(w => {
        words.push({ de: w.de, az: w.az, sub: w.sub || (w.type === 'sentence' ? 'cümlə' : ''), level: course.code, levelId: course.id });
      });
    });
  });
  return words;
}
